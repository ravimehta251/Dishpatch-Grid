#!/usr/bin/env python3
"""Build the performance report from captured k6 and database evidence, without credentials."""
import json
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
RESULTS=ROOT/'performance/results'

def fmt(value, digits=2):
    return '—' if value is None else f'{value:,.{digits}f}'

def main():
    rows=[]
    resources=[]
    queue_samples=[]
    burst_comparison={}
    for path in sorted(RESULTS.glob('*-summary.json')):
        data=json.loads(path.read_text())
        run=path.name.removesuffix('-summary.json')
        env_path=RESULTS/(run+'-environment.json')
        env=json.loads(env_path.read_text()) if env_path.exists() else {}
        metrics=data['metrics']; duration=metrics['http_req_duration']['values']
        delivery=env.get('delivery',{})
        if env.get('profile')=='burst' and delivery.get('deliveryP95Ms') is not None:
            burst_comparison[env.get('outboxPollMs',100)]=(run,delivery['deliveryP95Ms'])
        requests=metrics['http_reqs']['values']
        errors=metrics['unexpected_errors']['values']['rate']*100
        row=[run, str(env.get('workers',1)),str(env.get('outboxPollMs',100)),str(env.get('fanout',1)),str(requests['count']),fmt(requests['rate']),fmt(duration['p(95)']),fmt(duration['p(99)']),fmt(errors),str(delivery.get('delivered','—')),fmt(delivery.get('deliveryP95Ms')),str(delivery.get('terminal','—')),str(delivery.get('pending','—'))]
        rows.append('| '+' | '.join(row)+' |')
        metrics_path=RESULTS/(run+'-prometheus.json')
        if metrics_path.exists():
            recorded=json.loads(metrics_path.read_text(encoding='utf-8'))
            maxima=[]
            for key in ['outboxPending','deliveriesPending','consumerLag']:
                values=[float(value[1]) for series in recorded['queries'][key].get('data',{}).get('result',[]) for value in series.get('values',[]) if math.isfinite(float(value[1]))]
                maxima.append(fmt(max(values),0) if values else '—')
            queue_samples.append('| '+run+' | '+' | '.join(maxima)+' |')
        per_container={}
        for sample in env.get('resources',[]):
            for container in sample['containers']:
                name=container.get('Name','')
                if not any(tag in name for tag in ('dispatchgrid-api','dispatchgrid-worker')):continue
                record=per_container.setdefault(name,{'cpu':[],'memory':[]})
                record['cpu'].append(float(container['CPUPerc'].rstrip('%')))
                record['memory'].append(container['MemUsage'].split(' / ')[0])
        for name,record in sorted(per_container.items()):
            resources.append(f"| {run} | {name} | {fmt(sum(record['cpu'])/len(record['cpu']))}% | {fmt(max(record['cpu']))}% | {', '.join(dict.fromkeys(record['memory']))} |")
    comparison=''
    if 100 in burst_comparison and 20 in burst_comparison:
        before,after=burst_comparison[100],burst_comparison[20]
        comparison=f"\nObserved burst delivery p95 decreased from {before[1]:,.2f} ms (`{before[0]}`) to {after[1]:,.2f} ms (`{after[0]}`), a {(1-after[1]/before[1])*100:.1f}% reduction in these local runs. Both completed all 555 deliveries with no terminal or pending records. This comparison supports the polling change; it is not a universal production improvement guarantee.\n"
    report='''# Measured local performance

These are actual local runs, not production traffic or capacity guarantees. Run identifiers use UTC; the work was performed on 2026-10-18 in Asia/Calcutta. k6 summaries, database delivery aggregates, Docker resource samples and Prometheus captures are retained in `performance/results/`. Per-request samples and console output are generated by benchmark runs and excluded from Git.

## Environment

- Windows 11, Docker Desktop Linux/WSL2 engine 29.6.1; Intel Core i7-13620H (10 physical cores, 16 logical processors), 16,890,322,944 bytes host RAM. Docker reported approximately 7.62 GiB available.
- Java 21 / Spring Boot 3.5.16, PostgreSQL 16, Kafka 3.9.1, Redis 7, k6 1.0.0, local signature-verifying Python receiver with SQLite WAL.
- API and each worker container are limited to 768 MiB. Default Hikari pool: 16/process; worker consumers: 8/process; topics: 12 partitions. The local broker uses replication factor one.
- Payloads are small order-shaped JSON objects. The workload is a reproducible functionality/load probe, not a maximum-throughput claim. Browser checks and other development tooling shared this machine during some runs.

## Results

HTTP latency measures durable ingestion acknowledgement. End-to-end delivery latency measures `delivered_at - event.created_at` from PostgreSQL and therefore includes queueing, retries and receiver time. These are different measurements. A dash means that measurement was not captured in that run; it does not mean zero.

| Run (UTC) | Workers | Outbox poll ms | Fan-out | Requests | req/s | Ingestion p95 ms | Ingestion p99 ms | Unexpected errors % | Delivered | Delivery p95 ms | Terminal | Pending |
|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|
'''+ '\n'.join(rows)+'''

`quota_rejections` are recorded in each summary. Individual request samples are available locally after rerunning the benchmarks. The completed baseline and burst runs had no quota rejections. Retry fixtures deliberately cause HTTP 500 and may create terminal records; inspect each environment file's configured failures, attempts and final state. Only runs with a completed k6 summary appear above.

## Workloads and reproduction

```powershell
docker compose up -d --build
python scripts/demo.py
.\\scripts\\load-test.ps1 -Rate 5 -Duration 30s
python scripts/benchmark-suite.py
python scripts/collect-benchmark-metrics.py
python scripts/report-results.py
```

Linux/macOS: use `python3` and `bash scripts/load-test.sh`. The suite creates dedicated benchmark endpoints for the demo tenant, temporarily raises its development quota, and restores endpoint/quota/worker configuration in its cleanup path. The receiver remains a development fixture. Interrupted processes may require cleanup or a fresh demo tenant.

- Baseline: constant arrival, 5 events/s for 30 seconds, one destination.
- Burst: 1 → 10 → 40 → 10 events/s, three 10-second stages.
- Fan-out: 5 events/s for 20 seconds, three independent subscribed destinations.
- Slow receiver: 5 events/s for 20 seconds with 500 ms receiver delay.
- Retry volume: 5 events/s for 20 seconds with the first 100 HTTP attempts configured to fail; five attempts maximum, 1-second base/2-second capped backoff.
- One/two workers: the same 20 events/s workload for 20 seconds, 8 consumer threads per process. One endpoint still maps to one partition, so extra workers do not imply linear HTTP throughput.

## Resource samples during captured runs

Docker CPU percentages are per-container measurements, not process CPU utilization normalized across all host cores. Memory values below are the observed samples, not a fabricated high-water mark.

| Run | Container | Mean sampled CPU | Maximum sampled CPU | Observed memory |
|---|---|---:|---:|---|
'''+ '\n'.join(resources)+'''

## Maximum observed queue / lag samples

These values come from Prometheus samples, not from request latency. A dash indicates absent historical samples.

| Run | Outbox pending | Pending deliveries | Consumer lag |
|---|---:|---:|---:|
'''+ '\n'.join(queue_samples)+'''

## Findings and practical limits

The initial burst measurements showed seconds of delivery queueing while ingestion acknowledgements remained fast. The outbox publisher's five-message batch and original 100 ms poll interval bound the combined event/job notification rate; each accepted event creates at least two messages. The pending-outbox gauge and stored end-to-end latency expose this bottleneck. The final default is a configurable 20 ms polling delay; the table identifies the measured configuration for each run. Worker scaling should be evaluated alongside publisher throughput, partition keys and database pressure.
'''+comparison+'''

The slow-destination test exercises bounded resource use and durable backlog draining. A single endpoint maps to one Kafka partition; a 500 ms destination receiving 5 events/s builds a queue even with spare consumers. It does not prove fairness for every possible tenant distribution. Local runs do not establish internet latency, multi-node HA, long-duration leak behavior or production saturation limits. The `*-prometheus.json` files capture real backlog/lag/CPU samples over each available run window; missing historical series remain empty.

An earlier fan-out run (`20261017T205802Z-fanout`) was interrupted by host Docker shutdown and a bind-mount I/O error. Its incomplete artifacts were removed during repository cleanup and are excluded from successful measurements. No summary or result is invented for it.
'''
    (ROOT/'docs/performance.md').write_text(report,encoding='utf-8')
    print('Updated docs/performance.md from '+str(len(rows))+' completed k6 runs.')

if __name__=='__main__':main()
